#!/usr/bin/env python3
"""
PROJECT V — merge measured walkable routes into a navgraph (stdlib only, no geometry needed).

Reads datasets/spatial/<map>/mesh/<map>-routes.json (from tools/map-mesh/pipeline/route_map.py)
and writes, into datasets/spatial/<map>/<map>.navgraph.json:

  zone.anchor            a walkable standing point for the zone (game uu, z = floor), the end
                         point of every route that touches the zone
  edge.route             {waypoints: [[x,y,z],...] from -> to, lengthMeters, drops, provenance}
  edge.routeReverse      only when the way back differs (a one-way drop on one side)
  edge.distance*/time*   REPLACED by the route length at the map's movement speeds — the
                         walkable route wins over the previous straight-line / older measured
                         value, which is kept under edge.beforeRoute
  edge.routeStatus       "straight (...)" for an edge with no walkable route: it keeps its
                         previous length/time and a straight segment, flagged

build_map.py calls apply() for the geometry-derived maps. For Ascent (generated by
build-ascent.mjs) run this afterwards:

  python3 -I tools/map-processor/apply_routes.py ascent
"""
import json, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
PROV = "measured-on-mesh (walkable route)"


def _times(nav, meters):
    m = nav["movement"]
    return (round(meters / m["runSpeedMetersPerSec"] * 1000), round(meters / m["walkSpeedMetersPerSec"] * 1000))


def _route(nav, r):
    run, walk = _times(nav, r["lengthMeters"])
    return {"waypoints": r["waypoints"], "lengthMeters": r["lengthMeters"], "runTimeMs": run, "walkTimeMs": walk,
            "drops": r["drops"], "provenance": PROV}


def apply(nav, routes):
    """Mutates and returns nav. Idempotent."""
    anchors = routes["zoneAnchors"]
    for z in nav["zones"]:
        if z["id"] in anchors:
            z["anchor"] = anchors[z["id"]]
    by_key = {(e["from"], e["to"]): e for e in routes["edges"]}
    with_route, straight = 0, []
    for e in nav["edges"]:
        r = by_key.get((e["from"], e["to"]))
        if "beforeRoute" in e:                       # re-applying: start from the pre-route values
            e.update(e.pop("beforeRoute"))
        for k in ("route", "routeReverse", "routeStatus"):
            e.pop(k, None)
        if r is None or r["status"] != "route":
            reason = r["reason"] if r else "no route computed for this edge"
            e["routeStatus"] = f"straight ({reason})"
            straight.append(f"{e['from']}->{e['to']}")
            continue
        e["beforeRoute"] = {k: e[k] for k in ("distanceUnits", "distanceMeters", "runTimeMs", "walkTimeMs", "provenance")}
        e["route"] = _route(nav, r["route"])
        if r.get("routeReverse"):
            e["routeReverse"] = _route(nav, r["routeReverse"])
        e["distanceMeters"] = e["route"]["lengthMeters"]
        e["distanceUnits"] = round(e["route"]["lengthMeters"] * nav["movement"]["unitsPerMeter"])
        e["runTimeMs"], e["walkTimeMs"] = e["route"]["runTimeMs"], e["route"]["walkTimeMs"]
        e["provenance"] = PROV
        if e.get("kind") == "approx-link":
            # the zone graph could not join these two zones, but a walkable route between their
            # anchors does exist (typically across a third zone's area): it is a real edge now
            e["kind"] = "walk"
            e["note"] = "was a straight-line approx-link; replaced by a measured walkable route"
        with_route += 1
    nav["routes"] = {
        "provenance": "measured-on-mesh",
        "source": "tools/map-mesh/pipeline/route_map.py",
        "edgesWithWalkableRoute": with_route,
        "edgesFlaggedStraight": straight,
        "note": "edge.route.waypoints run from edge.from to edge.to in game uu and include both zone anchors. "
                "A bidirectional edge is walked back along the reversed waypoints unless edge.routeReverse exists. "
                "Edge length/time are the route's; the earlier values are under edge.beforeRoute.",
    }
    return nav


def dump_nav(nav, path):
    """json.dump(indent=2) with each [x, y, z] waypoint kept on one line."""
    text = json.dumps(nav, indent=2, ensure_ascii=False)
    text = re.sub(r"\[\s*(-?\d+(?:\.\d+)?),\s*(-?\d+(?:\.\d+)?),\s*(-?\d+(?:\.\d+)?)\s*\]", r"[\1, \2, \3]", text)
    with open(path, "w") as f:
        f.write(text + "\n")


def main(maps):
    for mp in maps:
        d = os.path.join(ROOT, "datasets", "spatial", mp)
        npath = os.path.join(d, f"{mp}.navgraph.json")
        nav = json.load(open(npath))
        apply(nav, json.load(open(os.path.join(d, "mesh", f"{mp}-routes.json"))))
        if mp == "ascent":
            nav["generatedBy"] = "tools/map-processor/build-ascent.mjs, then tools/map-processor/apply_routes.py"
        dump_nav(nav, npath)
        print(f"{mp}: {nav['routes']['edgesWithWalkableRoute']}/{len(nav['edges'])} edges with a walkable route; "
              f"straight: {nav['routes']['edgesFlaggedStraight']}")


if __name__ == "__main__":
    main(sys.argv[1:])
